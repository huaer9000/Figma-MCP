export const WRITE_GUIDELINES = `# 写入画布原则

本文是跨稿通用写法。某一页的坐标、色值和构图量测不要当作全局规则。

## 先看图文关系

动手前先判断每个区块属于哪一种，再写节点：

- **并排**：图和文是左右或上下两栏，互不重叠。
- **字压在图上**：标题或卡片叠在摄影、渐变或纹理上。
- **放大的独立图形**：产品截图、贴纸、超大 wordmark 本身是主设计，不是背景。
- **材质混合**：纹理叠在底色上（例如 multiply），不是一张配图。

不要把「附近有一张图、附近有一段字」做成随便上下叠。

字压图不等于字可以压在产品主体上。文案必须落在图的留白里。先量官网图的显示宽高和 \`object-fit\`，再定节点尺寸。把更瘦的产品图拉伸进正方形，主体会被放大并撞上标题。

## 复刻流程

按这个顺序做，不要先铺文案再补层：

1. 把官网视口调到目标宽度，按块判断图文关系。
2. 做铬清单：所有非透明背景、所有 \`border-width > 0\`、所有阴影和混合。
3. 按图层盘点列出每一层，再写节点。
4. 能流式排的用嵌套 Auto Layout；写完用 \`figma_export_node\` 按块对照。
5. 缺一层就还没还原完，不能只报节点已创建。

## 图层盘点

复刻不是「把文案和照片摆上去」。动手前按块列出每一层，写完按块导出对照。缺一层就还没还原完：

- **底**：区块全宽洗。纯色、渐变、摄影、纹理混合。纯色不能代替渐变或 multiply。还要核对照片是哪一张、什么构图：视频首帧和静态产品图可能完全不同，用错构图等于背景效果错了。
- **容器底**：卡片、行、aside 自己的填充，不等于页面白底。白卡旁边的浅灰底也是一层。
- **描边**：图、框、压在图上的 border。有图不等于没有描边。用 \`figma_set_stroke\`。
- **列表铬**：编号、分割线、项目间距。标题在不等于列表已还原。
- **饰件**：卡片图标、贴纸、引号、logo 箭头。短文旁边的 42px 图形也是一层。
- **字 / 图 / 按钮 / 效果**：字号字重、本机插图、按钮结构、圆角阴影。

动手前先做铬清单：所有非透明 \`background-color\`、所有 \`border-width > 0\`、所有 \`box-shadow\`。不要只靠肉眼扫标题和照片。

\`figma_set_fill\` 只写纯色。渐变和混合模式先落成本机 SVG/PNG，再用 \`figma_create_image\`，并如实说还不是原生填充。

## Auto Layout

- 区块和按钮用嵌套 Auto Layout，方便以后改文案。
- 只有压图、印章重叠才用 \`layoutPositioning: ABSOLUTE\`。先设绝对定位，再单独写 \`x\` / \`y\`；同一调用里先写坐标再设 ABSOLUTE，坐标会被流式布局吃掉。
- 打开水平 Auto Layout 后主轴默认 HUG。横排全宽区块必须 \`horizontalSizing: FIXED\`，或让子项 \`FILL\`。
- 按钮：Frame + Auto Layout，包住文案，主轴和交叉轴都居中。不要把标签做成按钮矩形的兄弟节点再估算坐标。
- 透明容器去底：\`figma_set_fill\` 传 \`clear: true\`。不要用 \`a: 0\` 的填充冒充。

## 插图与字体

- 摄影和 SVG 只走本机文件，用 \`figma_create_image\`。禁止远程 URL。
- 色块或渐变矩形不能当成已经插图。还没贴文件就如实说还没插图。
- 背景摄影要铺满容器。官网 \`object-fit: cover\` 或全宽背景，必须 \`scaleMode: FILL\`，并且图片节点与区块同宽同高。不要把宽幅图做成比容器窄的配图，两侧露出底色。
- 页脚、导航、目录必须按官网列齐全：每个分组标题和每条链接都要在。不能用简化几列或合并后的短名单冒充完整目录。
- 指定 \`fontName\` 失败会返回 \`FONT_NOT_AVAILABLE\`，不要改用别的字体。

## 核对与操作

- 先调 \`figma_status\`。插件面板必须开着；未连接时工具会立即失败。
- 写完用 \`figma_export_node\` 落到本地再对照，不能只报节点已创建。
- 切图和像素级读取必须给本机绝对路径；不要要求工具回传图片 base64。
- 一次不要并行太多写入，以免插件掉线。
`

